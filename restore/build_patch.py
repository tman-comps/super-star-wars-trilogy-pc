"""Build the data patch that restores scene $13 as a playable stage.
Only data is patched, and new data goes into end-of-bank padding (uninitialised EPROM bytes after the
last code/data in banks $81, $82 and $92), so nothing the shipped game reads is overwritten except:
  - setup record $12 (blank in the ROM) gets layer pointers,
  - the spawn-list pointer for scene $13,
  - two Seq_Table entries: (04,11)->(04,13) and a duplicate (dead) entry reused for (04,13)->(0A,22).
usage: build_patch.py rom > port/src/restore_patch.h      (or --script for ssw_script romw lines)"""
import os
import sys
sys.path[:0] = [__file__.rsplit("/", 1)[0], __file__.rsplit("/", 1)[0] + "/../tools"]
from lzss_pack import compress
from s13_layout import W, H, GRID

rom = open(sys.argv[1], "rb").read()
def off(a): return ((a >> 16) & 0x7F) * 0x8000 + (a & 0x7FFF)
def le(v): return bytes([v & 0xFF, v >> 8])
P = []   # (snes addr, bytes, expected original bytes or None for padding)

# 1. grid descriptor + compressed grid in bank $92 padding
DESC, GRIDP = 0x92FFC0, 0x92FFC6
blob = bytes([W, H, 0x10, 0x10, 0x00, 0x01]) + compress(GRID)
assert DESC + len(blob) <= 0x930000
P.append((DESC, blob, None))
# 2. layer record: a copy of scene $11's (bank $81:A166) pointing at the new grid, in bank $81 padding.
#    Copies are done at load time from the player's own ROM (COPY entries), then patched.
LREC = 0x81FFA0
src = rom[off(0x81A166):off(0x81A166) + 30]
assert src[14] == 0x92 and src[20:22] == le(0xA490) and src[22:24] == le(0xA4DF)
C = [(LREC, 0x81A166, 30)]
P.append((LREC + 20, le(DESC & 0xFFFF) + le(GRIDP & 0xFFFF), None))
# 3. setup record $12: copy of record $10 (scene $11) with the new layer record
R12 = 0x808A43 + 0x12 * 0x16
assert rom[off(R12)] == 0x12 and rom[off(R12) + 0x0E:off(R12) + 0x16] == b"\xFF" * 8
C.append((R12, 0x808A43 + 0x10 * 0x16, 0x16))
P.append((R12, b"\x12", None))
P.append((R12 + 0x0E, le(LREC & 0xFFFF) * 2, None))
# 4. spawn list in bank $82 padding
SPAWN = 0x82FED0
def rec(idx, *ops, spawn=True): return bytes([idx]) + b"".join(ops) + (b"\x1A\xED" if spawn else b"\x19\xED")
def pos(x, y): return b"\x07" + le(x) + le(y)
def typ(t): return bytes([0x09, t])
FLOOR1, FLOOR2 = 0x04B0, 0x05B0
script = b"".join([
    rec(0x00, pos(0x00C0, 0x04A0), typ(0x22)),              # player start   (original record)
    # The original records [01] and [02] place type $FE at ($0010,$0490) and ($0900,$0490). In play,
    # those objects slide inward towards Luke (about 2.5 px per frame), which fits the compactor
    # walls, but their unfinished code crashes the game when one reaches him. They are left out;
    # the port draws and runs the walls itself (restore.c).
    rec(0x03, pos(0x0380, 0x0450), typ(0x52), b"\x0A\x1D"),  # corridor fixtures, as in scene $11
    rec(0x04, pos(0x0300, FLOOR1), typ(0xC6), b"\x0E" + le(0x0200) + le(0x0480)),
    rec(0x05, pos(0x0400, FLOOR1), typ(0xCC), b"\x10\x0A"),
    rec(0x06, pos(0x0700, FLOOR1), typ(0xA8), b"\x0F" + le(FLOOR1 - 0xA0) + le(FLOOR1)),
    rec(0x07, pos(0x0880, FLOOR1), typ(0xD2), b"\x10\x08"),
    rec(0x08, pos(0x0600, FLOOR2), typ(0xC6), b"\x0E" + le(0x0500) + le(0x0900)),
    rec(0x09, pos(0x0780, FLOOR2), typ(0xCE), b"\x10\x08"),
    rec(0x0A, pos(0x0880, FLOOR2), typ(0xA8), b"\x0F" + le(FLOOR2 - 0xA0) + le(FLOOR2)),
    rec(0x0B, b"\x01\x08\x02" + le(0x0980) + le(FLOOR2), b"\x0C\xBB\xEC\x80", spawn=False),   # exit: stage clear
] + ([rec(0x0C, pos(0x0200, FLOOR1), typ(int(os.environ["SPAWN_TEST"], 16)))] if os.environ.get("SPAWN_TEST") else [])) + b"\x18\xED"
zone = le(0) + le(0xFFFF) + le(0) + le(0xFFFF) + le((SPAWN + 12) & 0xFFFF) + le(0xFFFF)
spawn = zone + script
assert SPAWN + len(spawn) <= 0x830000, len(spawn)
P.append((SPAWN, spawn, None))
SP = 0x82B0F5 + 0x13 * 2
P.append((SP, le(SPAWN & 0x7FFF), rom[off(SP):off(SP) + 2]))
# 5. sequence: detention block (04,11) -> restored stage (04,13) -> cutscene (0A,22)
SEQ = 0x809D4A
def seq_find(m, s):
    for i in range(0, 0x200, 4):
        if rom[off(SEQ) + i:off(SEQ) + i + 2] == bytes([m, s]): return SEQ + i
e11 = seq_find(0x04, 0x11); assert rom[off(e11) + 2:off(e11) + 4] == b"\x0A\x22"
P.append((e11 + 2, b"\x04\x13", b"\x0A\x22"))
dup = SEQ + 16; assert rom[off(dup):off(dup) + 4] == rom[off(dup) - 4:off(dup)]   # dead duplicate entry
P.append((dup, b"\x04\x13\x0A\x22", rom[off(dup):off(dup) + 4]))

if "--script" in sys.argv:
    img = bytearray(rom)
    for d, src_, n in C: img[off(d):off(d) + n] = rom[off(src_):off(src_) + n]
    for a, b, _ in P: img[off(a):off(a) + len(b)] = b
    seen = set()
    for a in [d for d, _, _ in C] + [a for a, _, _ in P]:
        if a in seen: continue
        seen.add(a)
        n = next((n for d, _, n in C if d == a), None) or next(len(b) for x, b, _ in P if x == a)
        print(f"romw {a:06X} {bytes(img[off(a):off(a) + n]).hex()}")
else:
    print("// generated by restore/build_patch.py - restored scene $13 (data patch, see CUT_CONTENT.md)")
    print("// Contains only the port's own data; copied pieces come from the player's ROM at load time.")
    print("typedef struct { unsigned addr; unsigned short len; const unsigned char* data; } RestorePatch;")
    print("typedef struct { unsigned dst, src; unsigned short len; } RestoreCopy;")
    print("static const RestoreCopy k_restore_copy[] = {")
    for d, src_, n in C: print(f"  {{0x{d:06X}, 0x{src_:06X}, {n}}},")
    print("};")
    for i, (a, b, o) in enumerate(P):
        print(f"static const unsigned char k_rp{i}[] = {{{','.join(str(x) for x in b)}}};")
    print("static const RestorePatch k_restore[] = {")
    for i, (a, b, o) in enumerate(P):
        print(f"  {{0x{a:06X}, {len(b)}, k_rp{i}}},")
    print("};")
